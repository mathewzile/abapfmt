// CLI

function walk(dir) {
  const out = [];
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (e.endsWith('Test.java')) out.push(p);
  }
  return out.sort();
}

export function importAll(javaTestsDir, outDir) {
  const rulesDir = join(javaTestsDir, 'rules');
  if (!existsSync(rulesDir)) throw new Error(`no 'rules' directory under ${javaTestsDir}`);
  if (existsSync(outDir)) rmSync(outDir, { recursive: true });
  const summary = { classes: 0, cases: 0, skipped: 0, notImported: [], skipReasons: new Map(), perClass: [] };
  const primitiveCounts = new Map();
  for (const file of walk(rulesDir)) {
    const source = readFileSync(file, 'utf8');
    for (const m of source.matchAll(/^\s+(?:[a-zA-Z]+\.)?([a-zA-Z]+)\(/gm)) {
      const key = /^config/.test(m[1]) ? null : m[1];
      if (key) primitiveCounts.set(key, (primitiveCounts.get(key) ?? 0) + 1);
    }
    const rel = relative(rulesDir, file).split('\\').join('/');
    let parsed;
    try { parsed = parseJavaTestClass(source); } catch (e) { summary.notImported.push(`${rel}: ${e.message}`); continue; }
    if (parsed.extendsName !== 'RuleTestBase' || !parsed.ruleId) { summary.notImported.push(`${rel}: does not extend RuleTestBase / no RuleID`); continue; }
    const group = dirname(rel);
    const target = join(outDir, group, basename(file, 'Test.java') + '.json');
    mkdirSync(dirname(target), { recursive: true });
    const { extendsName: _ignored, ...fixture } = parsed;
    writeFileSync(target, JSON.stringify({ ruleId: fixture.ruleId, testClass: fixture.testClass, defaults: fixture.defaults, cases: fixture.cases }, null, 1) + '\n');
    summary.classes++;
    summary.cases += fixture.cases.length;
    for (const c of fixture.cases) {
      if (c.skipped) {
        summary.skipped++;
        const key = c.skipped.replace(/\(.*$/, '').replace(/'.*$/, '').trim();
        summary.skipReasons.set(key, (summary.skipReasons.get(key) ?? 0) + 1);
      }
    }
  }
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'README.md'), README);
  return { summary, primitiveCounts };
}

const invoked = process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;
if (invoked) {
  const args = process.argv.slice(2);
  const opt = (name, fallback) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : fallback; };
  const javaTests = opt('--java-tests');
  if (!javaTests) {
    console.error('usage: node tools/import-java-fixtures.mjs --java-tests <.../com/sap/adt/abapcleaner> [--out <dir>]');
    process.exit(2);
  }
  const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
  const out = resolve(opt('--out', join(repoRoot, 'packages', 'core', 'test', 'engine', 'fixtures', 'rules')));
  const { summary, primitiveCounts } = importAll(resolve(javaTests), out);
  console.log(`imported ${summary.classes} classes, ${summary.cases} cases (${summary.skipped} skipped by importer) -> ${out}`);
  console.log('not imported:\n  ' + (summary.notImported.join('\n  ') || '(none)'));
  console.log('skip reasons:');
  for (const [k, v] of [...summary.skipReasons].sort((a, b) => b[1] - a[1])) console.log(`  ${v}\t${k}`);
  console.log('primitive call counts (statement-start calls in rule tests):');
  for (const [k, v] of [...primitiveCounts].sort((a, b) => b[1] - a[1]).filter(([k]) => /^[a-z]/.test(k))) console.log(`  ${v}\t${k}`);
}
