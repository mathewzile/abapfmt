#!/usr/bin/env node
// Imports the upstream abap-cleaner (Java, v1.29.0) rule tests as JSON fixtures.
//
// Every upstream rule test extends RuleTestBase and uses a small fixed vocabulary (buildSrc, buildExp,
// copyExpFromSrc, put*Around*, config*.setValue, testRule ...). This script lexes each Java test class
// (no regex on raw text: comments and string literals are handled by a real tokenizer), interprets the
// statements of each @Test method the way RuleTestBase would, and emits one fixture file per test class:
//
//   { ruleId, testClass, defaults, cases: [{ name, config, src, exp, flags, skipped? }] }
//
// - `defaults` are the config values set in the constructor / @BeforeEach setUp().
// - `config` of a case is defaults merged with the overrides set inside the test method.
// - Config names keep upstream's PascalCase (the part after `config`), e.g. `ParamCountAfterPerform`.
//   Enum values are stored as `EnumType.VALUE` strings.
// - `src` / `exp` are the fully built texts, INCLUDING the put*Around* wrappers (which RuleTestBase
//   applies in call order to both builders), with `\n` line separators (upstream uses `\r\n`).
// - A method that cannot be translated mechanically (loops, computed strings, helper calls with
//   arguments, config of other rules, cleanup ranges, ...) is emitted with `skipped: "<reason>"`.
//
// Usage: node tools/import-java-fixtures.mjs --java-tests <dir containing .../rules> [--out <dir>]
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

class Unsupported extends Error {}

const README = ['Generated by `tools/import-java-fixtures.mjs` from the SAP abap-cleaner v1.29.0 JUnit rule tests',
  '(test data derived from the upstream tests, Apache-2.0; see the repository NOTICE). Do not edit by hand.', ''].join('\n');

// ---------------------------------------------------------------------------------------------
// Lexer

const escapes = { n: '\n', t: '\t', r: '\r', b: '\b', f: '\f', '0': '\0', '"': '"', "'": "'", '\\': '\\' };

/** @returns {{t: 'id'|'str'|'num'|'p', v: string}[]} */
export function lexJava(source) {
  const tokens = [];
  let i = 0;
  const n = source.length;
  while (i < n) {
    const c = source[i];
    if (/\s/.test(c)) { i++; continue; }
    if (c === '/' && source[i + 1] === '/') { while (i < n && source[i] !== '\n') i++; continue; }
    if (c === '/' && source[i + 1] === '*') { const end = source.indexOf('*/', i + 2); i = end < 0 ? n : end + 2; continue; }
    if (c === '"' || c === "'") {
      let value = '';
      i++;
      while (i < n && source[i] !== c) {
        if (source[i] === '\\') {
          const e = source[i + 1];
          if (e === 'u') { value += String.fromCharCode(parseInt(source.slice(i + 2, i + 6), 16)); i += 6; continue; }
          if (!(e in escapes)) throw new Error(`unknown escape \\${e}`);
          value += escapes[e];
          i += 2;
        } else {
          value += source[i++];
        }
      }
      i++;
      tokens.push({ t: 'str', v: value });
      continue;
    }
    if (/[A-Za-z_$]/.test(c)) { let j = i + 1; while (j < n && /[\w$]/.test(source[j])) j++; tokens.push({ t: 'id', v: source.slice(i, j) }); i = j; continue; }
    if (/[0-9]/.test(c)) { let j = i + 1; while (j < n && /[\w.]/.test(source[j])) j++; tokens.push({ t: 'num', v: source.slice(i, j) }); i = j; continue; }
    tokens.push({ t: 'p', v: c });
    i++;
  }
  return tokens;
}

// ---------------------------------------------------------------------------------------------
// Expression evaluation (only what the tests use)

function findMatching(tokens, openIndex) {
  const open = tokens[openIndex].v;
  const close = { '(': ')', '{': '}', '[': ']' }[open];
  let depth = 0;
  for (let i = openIndex; i < tokens.length; i++) {
    const v = tokens[i].t === 'p' ? tokens[i].v : '';
    if (v === open) depth++;
    else if (v === close && --depth === 0) return i;
  }
  throw new Error('unbalanced ' + open);
}

/** Evaluates `"a" + "b" + CONSTANT` to a string. */
function evalString(tokens, ctx) {
  if (tokens.length === 0) throw new Unsupported('empty string expression');
  let result = '';
  let i = 0;
  let expectTerm = true;
  while (i < tokens.length) {
    const tok = tokens[i];
    if (expectTerm) {
      if (tok.t === 'str') { result += tok.v; i++; }
      else if (tok.t === 'num') { result += tok.v; i++; }
      else if (tok.t === 'p' && tok.v === '(') {
        const end = findMatching(tokens, i);
        result += evalString(tokens.slice(i + 1, end), ctx);
        i = end + 1;
      } else if (tok.t === 'id') {
        // constant, possibly qualified: NAME, ABAP.LINE_SEPARATOR
        let j = i;
        let name = tok.v;
        while (tokens[j + 1]?.v === '.' && tokens[j + 2]?.t === 'id') { name = tokens[j + 2].v; j += 2; }
        if (tokens[j + 1]?.v === '(' || tokens[j + 1]?.v === '.') throw new Unsupported(`computed string (${tokens.slice(i, j + 2).map((t) => t.v).join('')})`);
        if (name === 'LINE_SEPARATOR' || name === 'LINE_SEP') result += '\n';
        else if (name === 'NEWEST_RELEASE') result += '';
        else if (name === 'FALLBACK_RELEASE') result += 'fallback';
        else if (ctx.constants.has(name)) result += ctx.constants.get(name);
        else throw new Unsupported(`unknown constant ${name}`);
        i = j + 1;
      } else throw new Unsupported(`unsupported string term '${tok.v}'`);
      expectTerm = false;
    } else {
      if (tok.v !== '+') throw new Unsupported(`unsupported string operator '${tok.v}'`);
      i++;
      expectTerm = true;
    }
  }
  if (expectTerm) throw new Unsupported('dangling +');
  return result;
}

/** Evaluates a setValue argument: boolean, int, string, enum constant. */
function evalValue(tokens, ctx, enumValue) {
  if (tokens.length === 1 && tokens[0].t === 'id' && (tokens[0].v === 'true' || tokens[0].v === 'false')) return tokens[0].v === 'true';
  if (tokens.length === 1 && tokens[0].t === 'num' && /^\d+$/.test(tokens[0].v)) return Number(tokens[0].v);
  if (tokens.length === 2 && tokens[0].v === '-' && tokens[1].t === 'num' && /^\d+$/.test(tokens[1].v)) return -Number(tokens[1].v);
  if (enumValue && tokens.length >= 1 && tokens.every((t, k) => (k % 2 === 0 ? t.t === 'id' : t.v === '.')) && tokens.length % 2 === 1) {
    return tokens.map((t) => t.v).join('');
  }
  if (tokens.some((t) => t.t === 'str')) return evalString(tokens, ctx);
  throw new Unsupported(`non-literal config value '${tokens.map((t) => t.v).join(' ')}'`);
}

// ---------------------------------------------------------------------------------------------
// Class structure

/** Splits the class body into members. */
function parseClass(tokens) {
  let ci = tokens.findIndex((t, k) => t.t === 'id' && t.v === 'class' && tokens[k + 1]?.t === 'id');
  if (ci < 0) throw new Unsupported('no class declaration');
  const className = tokens[ci + 1].v;
  let extendsName = null;
  let i = ci + 2;
  while (tokens[i].v !== '{') { if (tokens[i].v === 'extends') extendsName = tokens[i + 1].v; i++; }
  const bodyEnd = findMatching(tokens, i);
  const members = [];
  const constants = new Map();
  i++;
  while (i < bodyEnd) {
    const start = i;
    let paren = 0;
    while (i < bodyEnd) {
      const v = tokens[i].t === 'p' ? tokens[i].v : '';
      if (v === '(') paren++;
      else if (v === ')') paren--;
      else if (paren === 0 && (v === ';' || v === '{')) break;
      i++;
    }
    const header = tokens.slice(start, i);
    if (tokens[i].v === ';') {
      const eq = header.findIndex((t) => t.v === '=');
      if (eq > 0 && header.some((t) => t.v === 'static') && header.some((t) => t.v === 'final')) {
        try { constants.set(header[eq - 1].v, evalString(header.slice(eq + 1), { constants })); } catch { /* not a string constant */ }
      }
      i++;
      continue;
    }
    const end = findMatching(tokens, i);
    const body = tokens.slice(i + 1, end);
    const annotations = [];
    for (let k = 0; k < header.length; k++) if (header[k].v === '@' && header[k + 1]?.t === 'id') annotations.push(header[k + 1].v);
    const paren0 = header.findIndex((t) => t.v === '(');
    const name = paren0 > 0 ? header[paren0 - 1].v : null;
    let paramCount = 0;
    if (paren0 >= 0) {
      const close = findMatching(header, paren0);
      paramCount = close === paren0 + 1 ? 0 : 1;
    }
    members.push({ name, annotations, body, paramCount, isCtor: name === className, isStatic: header.some((t) => t.v === 'static') });
    i = end + 1;
  }
  return { className, extendsName, members, constants };
}

/** Splits a method body into statements (token arrays). */
function splitStatements(tokens) {
  const statements = [];
  let cur = [];
  let paren = 0;
  let brace = 0;
  for (const tok of tokens) {
    cur.push(tok);
    const v = tok.t === 'p' ? tok.v : '';
    if (v === '(') paren++;
    else if (v === ')') paren--;
    else if (v === '{') brace++;
    else if (v === '}') {
      brace--;
      if (brace === 0 && paren === 0) { statements.push(cur); cur = []; }
    } else if (v === ';' && paren === 0 && brace === 0) { statements.push(cur); cur = []; }
  }
  if (cur.length) statements.push(cur);
  return statements;
}

const CONTROL = new Set(['for', 'while', 'if', 'else', 'switch', 'try', 'do', 'return', 'throw']);
const WRAPPERS = {
  putAnyMethodAroundSrcAndExp: ['  METHOD any_method.\n', '\n  ENDMETHOD.'],
  putAnyClassDefAroundSrcAndExp: ['CLASS any_class DEFINITION.\n  PUBLIC SECTION.\n', '\nENDCLASS.'],
  putAnyInterfaceDefAroundSrcAndExp: ['INTERFACE if_any_interface PUBLIC.\n', '\nENDINTERFACE.'],
  putAnyFormAroundSrcAndExp: ['FORM any_form.\n', '\nENDFORM.'],
};

/** Vocabulary handled by the interpreter; used for the primitive histogram in the CLI. */
export const SUPPORTED_PRIMITIVES = [
  'buildSrc', 'buildExp', 'copyExpFromSrc', ...Object.keys(WRAPPERS), 'deactivateSyntaxCheckAfterParse', 'deactivateRuleUseCheck',
  'setAbapReleaseOfCode', 'setReleaseRestrictionFromUI', 'testRule', '<rule>.config*.setValue', '<rule>.config*.setEnumValue',
  '<private no-arg helper method> (inlined)',
];

// java.lang.Character.isWhitespace: space/line/paragraph separators except NBSP (U+00A0, U+2007, U+202F),
// plus \t \n U+000B \f \r and U+001C..U+001F
const JAVA_WHITESPACE = new RegExp('[\t\n\u000B\f\r\u001C-\u001F \u1680\u2000-\u2006\u2008-\u200A\u2028\u2029\u205F\u3000]');

function trimEndJava(s) {
  let end = s.length;
  while (end > 0 && JAVA_WHITESPACE.test(s[end - 1])) end--;
  return s.slice(0, end);
}

function buildLine(current, line) {
  // RuleTestBase.buildCode: the separator is only added when the builder is already non-empty
  return (current.length > 0 ? current + '\n' : current) + trimEndJava(line);
}

class State {
  constructor(config) {
    this.config = { ...config };
    this.otherRules = {};
    this.src = '';
    this.exp = '';
    this.wrappers = [];
    this.flags = {};
    this.unsupported = null;
    this.testRuleCount = 0;
    this.cases = [];
  }
}

function callHead(stmt) {
  // returns { target, name, argTokens } for `[a.b.]name( args )`
  const paren = stmt.findIndex((t) => t.v === '(');
  if (paren < 1 || stmt[paren - 1].t !== 'id') return null;
  const close = findMatching(stmt, paren);
  const rest = stmt.slice(close + 1).filter((t) => t.v !== ';');
  const path = [];
  let k = paren - 1;
  path.unshift(stmt[k].v);
  while (k >= 2 && stmt[k - 1].v === '.' && stmt[k - 2].t === 'id') { path.unshift(stmt[k - 2].v); k -= 2; }
  if (k !== 0) return null; // something before the call (assignment, cast ...)
  return { path, argTokens: stmt.slice(paren + 1, close), trailing: rest };
}

function interpret(stmts, cls, ctx, state, methodName, depth = 0) {
  const { ruleVars, methodsByName } = ctx;
  for (const stmt of stmts) {
    if (stmt.length === 0) continue;
    try {
      const first = stmt[0];
      if (first.t === 'id' && CONTROL.has(first.v)) throw new Unsupported(`control flow (${first.v})`);
      // `var = (Type)getRule();`
      if (first.t === 'id' && stmt[1]?.v === '=' && stmt.some((t) => t.v === 'getRule')) {
        if (stmt.some((t) => t.v === 'profile')) {
          const at = stmt.findIndex((t, k) => t.v === 'RuleID' && stmt[k + 1]?.v === '.');
          ctx.otherRuleVars.set(first.v, at >= 0 ? stmt[at + 2].v : '?');
        } else ruleVars.add(first.v);
        continue;
      }
      if (first.t === 'id' && first.v === 'super' && stmt[1]?.v === '(') continue;
      const call = callHead(stmt);
      if (!call || call.trailing.length > 0) throw new Unsupported(`statement '${stmt.slice(0, 6).map((t) => t.v).join(' ')}'`);
      const { path, argTokens } = call;
      const name = path[path.length - 1];
      if (path.length === 3 && path[1].startsWith('config') && (name === 'setValue' || name === 'setEnumValue')) {
        const value = evalValue(argTokens, ctx, name === 'setEnumValue');
        const cfgName = path[1].slice('config'.length);
        if (ctx.otherRuleVars.has(path[0])) {
          const other = ctx.otherRuleVars.get(path[0]);
          (state.otherRules[other] ??= {})[cfgName] = value;
        } else if (ruleVars.has(path[0]) || path[0] === 'rule') {
          state.config[cfgName] = value;
        } else throw new Unsupported(`config on unknown variable (${path[0]}.${path[1]})`);
      } else if (path.length === 1 && name === 'buildSrc') {
        state.src = buildLine(state.src, evalString(argTokens, ctx));
      } else if (path.length === 1 && name === 'buildExp') {
        state.exp = buildLine(state.exp, evalString(argTokens, ctx));
      } else if (path.length === 1 && name === 'copyExpFromSrc') {
        state.exp = state.src;
      } else if (path.length === 1 && name in WRAPPERS) {
        const [start, end] = WRAPPERS[name];
        state.src = start + state.src + end;
        state.exp = start + state.exp + end;
        state.wrappers.push(name.replace(/^putAny|AroundSrcAndExp$/g, ''));
      } else if (path.length === 1 && name === 'deactivateSyntaxCheckAfterParse') {
        state.flags.syntaxCheckAfterParse = false;
      } else if (path.length === 1 && name === 'deactivateRuleUseCheck') {
        state.flags.ruleUseCheck = false;
      } else if (path.length === 1 && name === 'setAbapReleaseOfCode') {
        state.flags.abapRelease = evalString(argTokens, ctx);
      } else if (path.length === 1 && name === 'setReleaseRestrictionFromUI') {
        state.flags.releaseRestriction = argTokens.length === 1 && argTokens[0].t === 'num' ? Number(argTokens[0].v) : argTokens.map((t) => t.v).join('');
      } else if (path.length === 1 && name === 'testRule') {
        state.testRuleCount++;
        const suffix = state.testRuleCount > 1 ? `#${state.testRuleCount}` : '';
        state.cases.push({
          name: methodName + suffix,
          config: { ...state.config },
          ...(Object.keys(state.otherRules).length ? { otherRules: structuredClone(state.otherRules) } : {}),
          src: state.src,
          exp: state.exp,
          flags: { ...state.flags, ...(state.wrappers.length ? { wrappers: [...state.wrappers] } : {}) },
          ...(state.unsupported ? { skipped: state.unsupported } : {}),
        });
      } else if (path.length === 1 && methodsByName.has(name) && argTokens.length === 0 && !methodsByName.get(name).annotations.includes('Test')) {
        if (depth > 8) throw new Unsupported('helper recursion');
        interpret(splitStatements(methodsByName.get(name).body), cls, ctx, state, methodName, depth + 1);
      } else if (path.length === 1 && /^assert/.test(name)) {
        throw new Unsupported(`assertion (${name})`);
      } else {
        throw new Unsupported(`call ${path.join('.')}(...)`);
      }
    } catch (e) {
      if (!(e instanceof Unsupported)) throw e;
      state.unsupported ??= e.message;
    }
  }
}

/**
 * Parses one upstream Java rule test class.
 * @returns {{ruleId: string|null, testClass: string, extendsName: string|null, defaults: object, cases: object[]}}
 */
export function parseJavaTestClass(source) {
  const cls = parseClass(lexJava(source));
  // ruleId from super(RuleID.X)
  let ruleId = null;
  const ctor = cls.members.find((m) => m.isCtor);
  if (ctor) {
    const s = ctor.body.findIndex((t) => t.v === 'super');
    if (s >= 0 && ctor.body[s + 2]?.v === 'RuleID' && ctor.body[s + 4]?.t === 'id') ruleId = ctor.body[s + 4].v;
  }
  const ctx = {
    constants: cls.constants,
    ruleVars: new Set(),
    otherRuleVars: new Map(),
    methodsByName: new Map(cls.members.filter((m) => m.name && !m.isCtor).map((m) => [m.name, m])),
  };
  // defaults: constructor (after super) + @BeforeEach methods
  const defaultState = new State({});
  if (ctor) interpret(splitStatements(ctor.body), cls, ctx, defaultState, '<ctor>');
  for (const m of cls.members.filter((x) => x.annotations.includes('BeforeEach'))) {
    interpret(splitStatements(m.body), cls, ctx, defaultState, m.name);
  }
  const defaults = { ...defaultState.config };
  const cases = [];
  for (const m of cls.members.filter((x) => x.annotations.includes('Test'))) {
    const state = new State(defaults);
    state.otherRules = structuredClone(defaultState.otherRules);
    state.unsupported = defaultState.unsupported;
    interpret(splitStatements(m.body), cls, ctx, state, m.name);
    if (state.cases.length === 0) {
      cases.push({ name: m.name, config: { ...state.config }, src: '', exp: '', flags: {}, skipped: state.unsupported ?? 'no testRule() call' });
    } else {
      cases.push(...state.cases);
    }
  }
  return { ruleId, testClass: cls.className, extendsName: cls.extendsName, defaults, cases };
}

